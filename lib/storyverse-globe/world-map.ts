export const MAP_COLS = 72;
export const MAP_ROWS_COUNT = 36;

/** Generate all land dot positions as % coordinates on the map area. */
export function landDots(): { x: number; y: number }[] {
  const dots: { x: number; y: number }[] = [];
  for (let r = 0; r < MAP_ROWS.length; r++) {
    const row = MAP_ROWS[r] ?? "";
    for (let c = 0; c < row.length; c++) {
      if (row[c] === "#") {
        dots.push({
          x: ((c + 0.5) / MAP_COLS) * 100,
          y: ((r + 0.5) / MAP_ROWS_COUNT) * 100,
        });
      }
    }
  }
  return dots;
}

/**
 * Project (longitude, latitude) → % coordinates on the equirectangular map.
 * Used to place event pins at real geographic positions.
 */
export function projectToMap(lng: number, lat: number): { x: number; y: number } {
  return {
    x: ((lng + 180) / 360) * 100,
    y: ((90 - lat) / 180) * 100,
  };
}
